"""Вспомогательные функции перевода через локальную LLM.

Версия 0.1 использует Ollama, потому что так приложение может работать полностью
локально на Windows-машине с GPU. Модель по умолчанию — `qwen3:8b`: она
достаточно компактна для экспериментов и обычно подходит для короткого текста
на карточках настольных игр.
"""

import requests

# По умолчанию Ollama поднимает локальный HTTP API именно на этом адресе.
OLLAMA_URL = "http://localhost:11434/api/generate"

# Модель по умолчанию, рекомендованная для первого локального прототипа.
# Её можно заменить, передав другое значение в translate(..., model=...).
MODEL = "qwen3:8b"

# Промпт заставляет модель вести себя как локализатор настольных игр, а не как
# обычный переводчик. Также он просит вернуть только перевод, чтобы модуль
# отрисовки мог сразу вставить результат без удаления пояснений или префиксов.
PROMPT = """
Ты профессиональный локализатор настольных игр.

Переводи текст:
- естественно;
- как официальный перевод;
- не добавляй пояснений;
- сохраняй игровой стиль;
- сохраняй числа и игровые термины;
- возвращай только перевод.

Текст:
"""


def translate(text, model=MODEL):
    """Перевести один текстовый фрагмент через Ollama и вернуть только ответ."""
    # `stream=False` просит Ollama вернуть полный JSON-ответ за один раз.
    # В простом скрипте это удобнее, чем обрабатывать поток токенов.
    response = requests.post(
        OLLAMA_URL,
        json={
            "model": model,
            "prompt": PROMPT + text,
            "stream": False,
        },
        timeout=120,
    )

    # Показываем HTTP-проблемы явно: например, если Ollama не запущена или
    # нужная модель не установлена. Вызывающий код увидит обычное исключение requests.
    response.raise_for_status()

    return response.json()["response"].strip()
