"""Вспомогательные функции OCR для поиска текста на изображении карты.

PaddleOCR возвращает вложенную структуру с полигонами текста, уверенностью
распознавания и самим текстом. Для остальных модулей приложения мы приводим
эти данные к простому списку словарей:

{
    "text": "Deal 2 damage",
    "box": [[145, 370], [420, 370], [420, 420], [145, 420]],
}

Позже модуль отрисовки использует `box`, чтобы понять, какую часть изображения
нужно закрасить и куда вставить русский перевод.
"""

from paddleocr import PaddleOCR

# Первая версия прототипа рассчитана на английские исходные карты, поэтому OCR
# инициализируется с `lang="en"`. Если позже нужно переводить с другого языка,
# этот параметр можно заменить на поддерживаемый PaddleOCR код языка.
ocr = PaddleOCR(lang="en")


def extract_text(image_path):
    """Распознать текстовые блоки в `image_path` и вернуть упрощённые OCR-блоки."""
    # `ocr.ocr()` возвращает одну или несколько групп распознанных строк. Каждый
    # элемент содержит полигон текста по индексу 0 и данные о тексте по индексу 1.
    result = ocr.ocr(image_path)
    blocks = []

    for line in result:
        for item in line:
            # `box` — это четырёхточечный полигон вокруг найденного текста.
            box = item[0]

            # `item[1]` обычно выглядит как кортеж (распознанный_текст, уверенность).
            # Для перевода в версии 0.1 нам нужен только сам текст.
            text = item[1][0]

            blocks.append({
                "text": text,
                "box": box,
            })

    return blocks
