"""Главная точка входа для прототипа перевода карточек.

Этот файл специально остаётся небольшим: он только соединяет три шага,
которые реализованы в папке `modules/`:

1. OCR находит текст и координаты текстовых блоков на исходном изображении.
2. Переводчик отправляет каждый распознанный фрагмент в локальную модель Ollama.
3. Модуль отрисовки закрашивает старый текст и рисует русский перевод.

В версии 0.1 входной и выходной пути зафиксированы, чтобы первый запуск был
простым для пользователя Windows, который запускает проект вручную.
"""

from pathlib import Path

from modules.ocr import extract_text
from modules.renderer import render_translations
from modules.translator import translate

# Исходное изображение для первой версии прототипа.
# Перед запуском main.py нужно положить карточку для перевода именно сюда.
INPUT_IMAGE = Path("input/card.png")

# Итоговое изображение, которое создаёт сценарий обработки.
# Модуль отрисовки сам создаёт родительскую папку, если её нет.
OUTPUT_IMAGE = Path("output/card_ru.png")


def main():
    """Запустить полный сценарий обработки: OCR → перевод → отрисовка."""
    # PaddleOCR возвращает список блоков. Каждый блок содержит распознанный
    # текст и полигон, в котором этот текст был найден на изображении.
    blocks = extract_text(str(INPUT_IMAGE))

    # Переводим каждый распознанный фрагмент отдельно. Для версии 0.1 это
    # простой и предсказуемый вариант, хотя будущие версии смогут переводить
    # весь текст карты сразу, чтобы сохранять контекст между строками.
    for block in blocks:
        block["translation"] = translate(block["text"])
        print(f'{block["text"]} -> {block["translation"]}')

    # Рисуем все переведённые блоки поверх исходного изображения и сохраняем
    # готовую локализованную карту.
    render_translations(str(INPUT_IMAGE), blocks, str(OUTPUT_IMAGE))
    print(f"Готовая переведённая карта сохранена в {OUTPUT_IMAGE}")


if __name__ == "__main__":
    main()
